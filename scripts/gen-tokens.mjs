  ...Object.fromEntries(FAMILIES.map((f) => [`--k-swatch-${f.id}`, seed(f)])),

  // Type (tokens.md §4). Sizes clamp between mobile and desktop.
  '--k-font': "'Inter Variable', Inter, system-ui, -apple-system, 'Segoe UI', Roboto, sans-serif",
  '--k-mono': "ui-monospace, 'SF Mono', Menlo, Consolas, monospace",
