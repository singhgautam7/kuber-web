/**
 * Generates src/styles/tokens.css from src/lib/themes.ts (the app's theme
 * engine, ported) and the static tokens in design web-v1/tokens.md.
 *
 * Run with: bun run scripts/gen-tokens.mjs (dev and build run it first).
 *
 * This file and tokens.css are the only places a colour value is written.
 */
import { writeFileSync } from 'node:fs';
import { FAMILIES, accessible, seed } from '../src/lib/themes.ts';

const out = new URL('../src/styles/tokens.css', import.meta.url);
const block = (sel, vars) => `${sel} {\n${Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}`;
const roles = (p) => Object.fromEntries(Object.entries(p).map(([k, v]) => [`--k-${k}`, v]));

// Fixed per mode, never per family: app icon (icon/icon.md) and category tiles
// (Web v1 Home frames H1a / H1b).
